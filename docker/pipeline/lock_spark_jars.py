"""Writes docker/pipeline/spark-jars.lock: every JAR the Spark session needs, with its URL
on Maven Central and its SHA-256.

Resolves the coordinates in src/arkham/spark_packages.py with Spark's own dependency
resolution (Ivy, the same one behind --packages), then checks that each resolved JAR is
byte-for-byte the file at its Maven Central URL. The image build (fetch_spark_jars.py)
downloads exactly these files and verifies their checksums, without starting Spark.

Run it after changing spark_packages.py: `make lock-jars` (needs the pipeline image and
network access), then `make build`.

Usage: python lock_spark_jars.py <spark_packages.py> <spark-jars.lock>
"""

from __future__ import annotations

import hashlib
import http.client
import importlib.util
import json
import sys
import tempfile
import time
import urllib.request
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

REPOSITORY = "https://repo1.maven.org/maven2"


def load_packages(module_path: Path) -> tuple[str, ...]:
    spec = importlib.util.spec_from_file_location("spark_packages", module_path)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"Cannot load {module_path}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module.SPARK_PACKAGES


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def resolve(packages: tuple[str, ...], ivy_dir: Path) -> list[dict[str, str]]:
    """Resolves the packages with Ivy and returns one entry per resolved JAR."""
    from pyspark.sql import SparkSession  # noqa: PLC0415 - only needed here

    spark = (
        SparkSession.builder.master("local[1]")
        .config("spark.jars.packages", ",".join(packages))
        .config("spark.jars.ivy", str(ivy_dir))
        .config("spark.ui.enabled", "false")
        .getOrCreate()
    )
    spark.stop()
    retrieved = {path.name for path in (ivy_dir / "jars").glob("*.jar")}
    jars = []
    # Ivy's cache keeps each artifact at cache/<organisation>/<module>/<type>s/<module>-<rev>.jar
    for path in sorted((ivy_dir / "cache").glob("*/*/*/*.jar")):
        organisation, module, kind = path.parts[-4], path.parts[-3], path.parts[-2]
        if kind not in ("jars", "bundles") or not path.name.startswith(f"{module}-"):
            continue
        revision = path.name[len(module) + 1 : -len(".jar")]
        file_name = f"{organisation}_{module}-{revision}.jar"
        if file_name not in retrieved:
            continue
        url = f"{REPOSITORY}/{organisation.replace('.', '/')}/{module}/{revision}/{path.name}"
        jars.append(
            {
                "coordinate": f"{organisation}:{module}:{revision}",
                "file": file_name,
                "url": url,
                "sha256": sha256(path.read_bytes()),
            }
        )
    found = {jar["file"] for jar in jars}
    if found != retrieved:
        raise RuntimeError(f"Could not map these JARs to Maven coordinates: {retrieved - found}")
    return jars


def check_against_repository(jar: dict[str, str], attempts: int = 3) -> None:
    """The JAR at the URL must be the one Ivy resolved. Retries cut connections."""
    for attempt in range(1, attempts + 1):
        try:
            with urllib.request.urlopen(jar["url"], timeout=120) as response:  # noqa: S310
                remote = sha256(response.read())
            break
        except (OSError, http.client.HTTPException) as error:
            if attempt == attempts:
                raise RuntimeError(f"Could not download {jar['url']}: {error}") from error
            time.sleep(2 * attempt)
    if remote != jar["sha256"]:
        raise RuntimeError(f"{jar['url']} differs from the JAR Ivy resolved")


def main(module_path: Path, lock_path: Path) -> None:
    packages = load_packages(module_path)
    with tempfile.TemporaryDirectory(prefix="ivy-") as ivy_dir:
        jars = resolve(packages, Path(ivy_dir))
    with ThreadPoolExecutor(max_workers=4) as pool:
        list(pool.map(check_against_repository, jars))
    lock = {
        "comment": "Generated by docker/pipeline/lock_spark_jars.py (make lock-jars). Do not edit.",
        "packages": list(packages),
        "jars": jars,
    }
    lock_path.write_text(json.dumps(lock, indent=2) + "\n")
    print(f"Locked {len(jars)} JARs for {', '.join(packages)} in {lock_path}")


if __name__ == "__main__":
    main(Path(sys.argv[1]), Path(sys.argv[2]))
